'use client';

import { useEffect } from 'react';

// Specific Workbox cache names created by next-pwa in this application
const APP_CACHE_IDENTIFIERS = [
    'workbox-precache',
    'start-url',
    'google-fonts-webfonts',
    'google-fonts-stylesheets',
    'static-font-assets',
    'static-image-assets',
    'next-image',
    'static-audio-assets',
    'static-video-assets',
    'static-js-assets',
    'static-style-assets',
    'next-data',
    'static-data-assets',
    'apis',
    'others',
];

/**
 * ServiceWorkerRegistration:
 * Targetedly unregisters only this app's Workbox/next-pwa service worker ('/sw.js')
 * and purges only its corresponding Workbox runtime caches.
 * Does not touch unrelated service workers or third-party caches.
 */
export function ServiceWorkerRegistration() {
    useEffect(() => {
        if (typeof window === 'undefined') return;

        // 1. Unregister only this app's Service Worker (/sw.js)
        if ('serviceWorker' in navigator) {
            navigator.serviceWorker.getRegistrations().then((registrations) => {
                for (const registration of registrations) {
                    const scriptUrl =
                        registration.active?.scriptURL ||
                        registration.installing?.scriptURL ||
                        registration.waiting?.scriptURL ||
                        '';

                    // Ensure we only unregister this app's service worker
                    if (scriptUrl.endsWith('/sw.js') || scriptUrl.includes('workbox')) {
                        registration
                            .unregister()
                            .then((unregistered) => {
                                if (unregistered) {
                                    console.log('[SW Cleanup] Successfully unregistered app service worker:', scriptUrl);
                                }
                            })
                            .catch((error) => {
                                console.warn('[SW Cleanup] Failed to unregister app service worker:', error);
                            });
                    }
                }
            }).catch(() => {});
        }

        // 2. Clear only caches generated by this app's Workbox configuration
        if ('caches' in window) {
            caches.keys().then((cacheNames) => {
                for (const cacheName of cacheNames) {
                    const isAppCache = APP_CACHE_IDENTIFIERS.some(
                        (identifier) => cacheName === identifier || cacheName.startsWith(`${identifier}-`)
                    );

                    if (isAppCache) {
                        caches.delete(cacheName).then(() => {
                            console.log('[SW Cleanup] Deleted app cache:', cacheName);
                        }).catch(() => {});
                    }
                }
            }).catch(() => {});
        }
    }, []);

    return null;
}


